namespace Domain.Enums.Floorball;

/// <summary>
/// Represents the possible results of a floorball game
/// </summary>
public enum FloorballGameResult
{
    /// <summary>
    /// The team won the game
    /// </summary>
    Win,

    /// <summary>
    /// The team lost the game
    /// </summary>
    Loss,

    /// <summary>
    /// The game ended in a tie
    /// </summary>
    Tie
}
