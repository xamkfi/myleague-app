namespace Domain.Enums.Floorball;

/// <summary>
/// Represents the different playing positions in floorball
/// </summary>
public enum FloorballPosition
{
    /// <summary>
    /// No specific position assigned
    /// </summary>
    None = 0,

    /// <summary>
    /// Forward/striker position
    /// </summary>
    Forward = 1,
    
    /// <summary>
    /// Center position
    /// </summary>
    Center = 2,
    
    /// <summary>
    /// Defender position
    /// </summary>
    Defender = 3,
    
    /// <summary>
    /// Goalkeeper position
    /// </summary>
    Goalkeeper = 4
} 
