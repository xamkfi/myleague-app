namespace Domain.Enums.Hockey
{
    /// <summary>
    /// Represents the different positions in hockey
    /// </summary>
    public enum HockeyPosition
    {
        /// <summary>
        /// No specific position assigned
        /// </summary>
        None = 0,

        /// <summary>
        /// Unspecified forward position
        /// </summary>
        Forward = 1,

        /// <summary>
        /// Center position
        /// </summary>
        Center = 2,

        /// <summary>
        /// Right wing forward position
        /// </summary>
        RightForward = 3,

        /// <summary>
        /// Left wing forward position
        /// </summary>
        LeftForward = 4,

        /// <summary>
        /// Unspecified defender position
        /// </summary>
        Defender = 5,

        /// <summary>
        /// Left wing defender position
        /// </summary>
        LeftDefender = 6,

        /// <summary>
        /// Right wing defender position
        /// </summary>
        RightDefender = 7,

        /// <summary>
        /// Goalkeeper position
        /// </summary>
        Goalkeeper = 8,

        /// <summary>
        /// Coach position
        /// </summary>
        Coach = 9
    }
}
